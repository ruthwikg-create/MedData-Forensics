"""Multiclass MedMNIST-like regression using fabricated images only.

Purpose: verify CPU model compatibility with seven labels and current scikit-learn,
not accuracy or biomedical validity.
"""
import io
import numpy as np
from fastapi.testclient import TestClient

from backend.api import app
from backend.worker import run_one


def test_seven_class_npz_import_and_cpu_baseline(monkeypatch):
    monkeypatch.setenv('MDF_NO_AUTOWORKER','1')
    rng=np.random.default_rng(20261113)
    arrays={}
    for split,per_class in [('train',8),('val',2),('test',3)]:
        labels=np.repeat(np.arange(7),per_class).astype(np.uint8)
        # Generate independent random images. Do not infer research performance.
        images=rng.integers(0,256,(len(labels),28,28,3),dtype=np.uint8)
        arrays[split+'_images']=images
        arrays[split+'_labels']=labels.reshape(-1,1)
    stream=io.BytesIO()
    np.savez_compressed(stream,**arrays)
    stream.seek(0)
    with TestClient(app) as client:
        imported=client.post('/api/datasets/import',
            data={'name':'Seven class synthetic compatibility','source':'Generated by regression test',
                  'license':'Generated synthetic images only','max_per_split':'200'},
            files={'file':('sevenclass.npz',stream,'application/octet-stream')})
        assert imported.status_code==200,imported.text
        did=imported.json()['dataset_id']
        readiness=client.get(f'/api/datasets/{did}/baseline-readiness').json()
        assert readiness['ready'],readiness
        assert len(readiness['training_class_counts'])==7
        created=client.post(f'/api/datasets/{did}/experiments',json={'kind':'baseline','config':{'seed':42}})
        assert created.status_code==200,created.text
        assert run_one()
        job=client.get(f"/api/jobs/{created.json()['job_id']}").json()
        assert job['status']=='completed',job
        experiment=client.get(f"/api/experiments/{created.json()['experiment_id']}").json()
        assert experiment['checkpoint_available'] is True
        assert len(experiment['result']['test']['metrics']['confusion_matrix'])==7
        assert experiment['result']['test']['metrics']['n']==21
